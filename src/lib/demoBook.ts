export function demoBookToCsv(prospects: Prospect[]): string {
  const headers = [
    "Name",
    "Email",
    "Phone",
    "Company",
    "Title",
    "Segment",
    "Source",
    "Last Touch",
    "Notes",
    "Value",
    "LinkedIn",
  ];
  const lines = [headers.join(",")];
  for (const p of prospects) {
    const vals = [
      p.name,
      p.email ?? "",
      p.phone ?? "",
      p.company ?? "",
      p.title ?? "",
      p.segment ?? "",
      p.source ?? "",
      p.lastTouch ?? "",
      p.notes ?? "",
      p.estimatedValue ?? "",
      p.linkedin ?? "",
    ].map((v) => `"${String(v).replace(/"/g, '""')}"`);
    lines.push(vals.join(","));
  }
  return lines.join("\n");
}
