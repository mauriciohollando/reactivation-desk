import type { Prospect } from "./types";

function isoDaysAgo(days: number) {
  const d = new Date();
  d.setDate(d.getDate() - days);
  return d.toISOString().slice(0, 10);
}

function row(
  partial: Omit<Prospect, "raw" | "id"> & { id: string },
): Prospect {
  const p: Prospect = {
    ...partial,
    raw: {},
  };
  p.raw = {
    Name: p.name,
    Email: p.email ?? "",
    Phone: p.phone ?? "",
    Company: p.company ?? "",
    Title: p.title ?? "",
    Segment: p.segment ?? "",
    Source: p.source ?? "",
    "Last Touch": p.lastTouch ?? "",
    Notes: p.notes ?? "",
    Value: p.estimatedValue ?? "",
    LinkedIn: p.linkedin ?? "",
  };
  return p;
}

